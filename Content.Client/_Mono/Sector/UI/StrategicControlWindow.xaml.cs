using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Sector;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Mono.Sector.UI;

[GenerateTypedNameReferences]
public sealed partial class StrategicControlWindow : FancyWindow
{
    public event Action? OnClaim;
    public event Action? OnRelinquish;
    public event Action<bool, bool, Dictionary<StrategicResource, int>>? OnApplyTrade;

    public StrategicControlWindow()
    {
        RobustXamlLoader.Load(this);

        ClaimButton.OnPressed += _ => OnClaim?.Invoke();
        RelinquishButton.OnPressed += _ => OnRelinquish?.Invoke();
        ApplyTradeButton.OnPressed += _ =>
        {
            int.TryParse(FuelPriceEdit.Text, out var fuel);
            int.TryParse(MunitionsPriceEdit.Text, out var munitions);
            int.TryParse(PartsPriceEdit.Text, out var parts);

            OnApplyTrade?.Invoke(
                BuyCheck.Pressed,
                SellCheck.Pressed,
                new Dictionary<StrategicResource, int>
                {
                    { StrategicResource.Fuel, fuel },
                    { StrategicResource.Munitions, munitions },
                    { StrategicResource.Parts, parts },
                });
        };
    }

    public void UpdateState(StrategicControlBoundUserInterfaceState state)
    {
        NameLabel.Text = state.OutpostName;
        OwnerLabel.Text = Loc.GetString("strategic-ui-owner",
            ("owner", state.Owner?.Id ?? Loc.GetString("strategic-ui-owner-none")));

        var statusExtra = state.Relinquishing
            ? Loc.GetString("strategic-control-status-relinquishing")
            : state.ClaimProgress is > 0f and < 1f
                ? Loc.GetString("strategic-control-status-claiming")
                : string.Empty;

        ProgressLabel.Text = Loc.GetString("strategic-control-progress",
            ("percent", (state.ClaimProgress * 100f).ToString("F0")),
            ("status", statusExtra));

        CoordsLabel.Text = Loc.GetString("strategic-ui-coords",
            ("x", state.WorldPos.X.ToString("F0")),
            ("y", state.WorldPos.Y.ToString("F0")));

        state.Pools.TryGetValue(StrategicResource.Fuel, out var fuel);
        state.Pools.TryGetValue(StrategicResource.Munitions, out var munitions);
        state.Pools.TryGetValue(StrategicResource.Parts, out var parts);
        PoolsLabel.Text = Loc.GetString("strategic-control-pools",
            ("fuel", fuel), ("munitions", munitions), ("parts", parts));

        BuyCheck.Pressed = state.BuyEnabled;
        SellCheck.Pressed = state.SellEnabled;
        FuelPriceEdit.Text = state.ResourcePrices.GetValueOrDefault(StrategicResource.Fuel).ToString();
        MunitionsPriceEdit.Text = state.ResourcePrices.GetValueOrDefault(StrategicResource.Munitions).ToString();
        PartsPriceEdit.Text = state.ResourcePrices.GetValueOrDefault(StrategicResource.Parts).ToString();
    }

    private static string ControlLabel(SectorControl c) => c switch
    {
        SectorControl.Controlled => Loc.GetString("strategic-ui-control-controlled"),
        SectorControl.Contested => Loc.GetString("strategic-ui-control-contested"),
        _ => Loc.GetString("strategic-ui-control-unclaimed"),
    };
}
