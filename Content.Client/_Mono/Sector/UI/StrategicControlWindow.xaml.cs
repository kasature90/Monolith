using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Sector;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Mono.Sector.UI;

[GenerateTypedNameReferences]
public sealed partial class StrategicControlWindow : FancyWindow
{
    private const float PriceStep = 100f;

    public event Action? OnClaim;
    public event Action? OnRelinquish;
    public event Action<float>? FuelPriceChanged;
    public event Action<float>? AmmoPriceChanged;
    public event Action<float>? PartPriceChanged;
    public event Action<bool, bool>? TradeTogglesChanged;

    private bool _suppressSliderEvents;
    private bool _pricesSeeded;

    public StrategicControlWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        ClaimButton.OnPressed += _ => OnClaim?.Invoke();
        RelinquishButton.OnPressed += _ => OnRelinquish?.Invoke();

        BuyCheck.OnToggled += args =>
            TradeTogglesChanged?.Invoke(args.Pressed, SellCheck.Pressed);
        SellCheck.OnToggled += args =>
            TradeTogglesChanged?.Invoke(BuyCheck.Pressed, args.Pressed);

        WirePrice(FuelPriceLabel, FuelPriceSlider, FuelPriceDecrease, FuelPriceIncrease,
            v => FuelPriceChanged?.Invoke(v));
        WirePrice(AmmoPriceLabel, AmmoPriceSlider, AmmoPriceDecrease, AmmoPriceIncrease,
            v => AmmoPriceChanged?.Invoke(v));
        WirePrice(PartPriceLabel, PartPriceSlider, PartPriceDecrease, PartPriceIncrease,
            v => PartPriceChanged?.Invoke(v));
    }

    private void WirePrice(LineEdit label, Slider slider, Button decrease, Button increase, Action<float> onChanged)
    {
        label.OnFocusExit += _ => CommitText(label, slider, onChanged);
        label.OnTextEntered += _ => CommitText(label, slider, onChanged);

        slider.OnValueChanged += _ =>
        {
            if (_suppressSliderEvents)
                return;

            var value = MathF.Round(slider.Value);
            if (!label.HasKeyboardFocus())
                label.Text = ((int)value).ToString();
            onChanged(value);
        };

        decrease.OnPressed += _ => Nudge(slider, label, -PriceStep, onChanged);
        increase.OnPressed += _ => Nudge(slider, label, PriceStep, onChanged);
    }

    private void CommitText(LineEdit label, Slider slider, Action<float> onChanged)
    {
        if (!float.TryParse(label.Text, out var num))
            return;

        num = Math.Clamp(num, slider.MinValue, slider.MaxValue);
        SetSliderSilent(slider, num);
        label.Text = ((int)num).ToString();
        onChanged(num);
    }

    private void Nudge(Slider slider, LineEdit label, float delta, Action<float> onChanged)
    {
        var value = Math.Clamp(MathF.Round(slider.Value + delta), slider.MinValue, slider.MaxValue);
        SetSliderSilent(slider, value);
        label.Text = ((int)value).ToString();
        onChanged(value);
    }

    private void SetSliderSilent(Slider slider, float value)
    {
        _suppressSliderEvents = true;
        slider.Value = value;
        _suppressSliderEvents = false;
    }

    private void SetPriceRow(LineEdit label, Slider slider, float price)
    {
        if (!label.HasKeyboardFocus())
            label.Text = ((int)price).ToString();

        SetSliderSilent(slider, Math.Clamp(price, slider.MinValue, slider.MaxValue));
    }

    public void UpdateState(StrategicControlBoundUserInterfaceState state)
    {
        NameLabel.Text = state.OutpostName;
        OwnerLabel.Text = Loc.GetString("strategic-ui-owner",
            ("owner", state.Owner?.Id ?? Loc.GetString("strategic-ui-owner-none")));

        var statusExtra = state.Relinquishing
            ? Loc.GetString("strategic-control-status-relinquishing")
            : state.ClaimProgress is > 0f and < 1f
                ? Loc.GetString("strategic-control-status-claiming")
                : string.Empty;

        ProgressLabel.Text = Loc.GetString("strategic-control-progress",
            ("percent", (state.ClaimProgress * 100f).ToString("F0")),
            ("status", statusExtra));

        CoordsLabel.Text = Loc.GetString("strategic-ui-coords",
            ("x", state.WorldPos.X.ToString("F0")),
            ("y", state.WorldPos.Y.ToString("F0")));

        state.Pools.TryGetValue(StrategicResource.Fuel, out var fuel);
        state.Pools.TryGetValue(StrategicResource.Munitions, out var munitions);
        state.Pools.TryGetValue(StrategicResource.Parts, out var parts);
        PoolsLabel.Text = Loc.GetString("strategic-control-pools",
            ("fuel", fuel), ("munitions", munitions), ("parts", parts));

        if (_pricesSeeded)
            return;

        BuyCheck.Pressed = state.BuyEnabled;
        SellCheck.Pressed = state.SellEnabled;

        SetPriceRow(FuelPriceLabel, FuelPriceSlider, state.ResourcePrices[StrategicResource.Fuel]);
        SetPriceRow(AmmoPriceLabel, AmmoPriceSlider, state.ResourcePrices[StrategicResource.Munitions]);
        SetPriceRow(PartPriceLabel, PartPriceSlider, state.ResourcePrices[StrategicResource.Parts]);
        _pricesSeeded = true;
    }
}
