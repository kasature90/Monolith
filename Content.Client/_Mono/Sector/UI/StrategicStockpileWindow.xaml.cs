using Content.Client.UserInterface.Controls;
using Content.Shared._Mono.Sector;
using Content.Shared._NF.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Mono.Sector.UI;

[GenerateTypedNameReferences]
public sealed partial class StrategicStockpileWindow : FancyWindow
{
    public event Action<StrategicResource, int>? OnBuy;
    public event Action<int>? OnWithdraw;

    public StrategicStockpileWindow()
    {
        RobustXamlLoader.Load(this);

        BuyFuelButton.OnPressed += _ => OnBuy?.Invoke(StrategicResource.Fuel, 1);
        BuyMunitionsButton.OnPressed += _ => OnBuy?.Invoke(StrategicResource.Munitions, 1);
        BuyPartsButton.OnPressed += _ => OnBuy?.Invoke(StrategicResource.Parts, 1);

        WithdrawButton.OnPressed += _ =>
        {
            int.TryParse(WithdrawEdit.Text, out var amount);
            if (amount > 0)
                OnWithdraw?.Invoke(amount);
        };
    }

    public void UpdateState(StrategicStockpileBoundUserInterfaceState state)
    {
        NameLabel.Text = state.OutpostName;
        BalanceLabel.Text = Loc.GetString("strategic-stockpile-balance", ("balance", state.Balance));
        PassiveLabel.Text = Loc.GetString("strategic-stockpile-passive", ("amount", state.PassiveIncome), ("time", state.PassiveInterval));

        state.Pools.TryGetValue(StrategicResource.Fuel, out var fuel);
        state.Pools.TryGetValue(StrategicResource.Munitions, out var munitions);
        state.Pools.TryGetValue(StrategicResource.Parts, out var parts);
        PoolsLabel.Text = Loc.GetString("strategic-control-pools",
            ("fuel", fuel),
            ("munitions", munitions),
            ("parts", parts));

        var fp = state.ResourcePrices.GetValueOrDefault(StrategicResource.Fuel);
        var mp = state.ResourcePrices.GetValueOrDefault(StrategicResource.Munitions);
        var pp = state.ResourcePrices.GetValueOrDefault(StrategicResource.Parts);
        FuelPriceLabel.Text = BankSystemExtensions.ToSpesoString(fp);
        AmmoPriceLabel.Text = BankSystemExtensions.ToSpesoString(mp);
        PartsPriceLabel.Text = BankSystemExtensions.ToSpesoString(pp);

        BuyFuelButton.Disabled = !state.BuyEnabled;
        BuyMunitionsButton.Disabled = !state.BuyEnabled;
        BuyPartsButton.Disabled = !state.BuyEnabled;

        WithdrawButton.Disabled = !state.IsOwner;
        WithdrawEdit.Editable = state.IsOwner;
        OwnerOnlyLabel.Text = state.IsOwner
            ? string.Empty
            : Loc.GetString("strategic-stockpile-owner-only");
    }
}
