using Content.Client._Mono.Sector;
using Content.Shared._Mono.Sector;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._Mono.Sector.UI;

[GenerateTypedNameReferences]
public sealed partial class StrategicScreen : Control
{
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IEntityManager _entManager = default!;

    private SectorMapSystem SectorMap => _entManager.System<SectorMapSystem>();
    private readonly StrategicMapControl _map = new();
    private SectorMapStateMessage? _state;
    private NetEntity? _selected;
    private TimeSpan _nextRefresh;

    public StrategicScreen()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        MapHost.AddChild(_map);
        _map.OnOutpostClicked += OnOutpostClicked;

        RefreshButton.OnPressed += _ => RequestRefresh();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        SectorMap.OnState += OnState;
        RequestRefresh();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        SectorMap.OnState -= OnState;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_timing.CurTime < _nextRefresh)
            return;

        _nextRefresh = _timing.CurTime + TimeSpan.FromSeconds(5);
        RequestRefresh();
    }

    private void RequestRefresh()
    {
        SectorMap.Request();
    }

    private void OnState(SectorMapStateMessage state)
    {
        _state = state;
        RebuildList();
        _map.SetState(state, _selected);
        if (_selected != null)
            ShowDetail(_selected.Value);
    }

    private void RebuildList()
    {
        OutpostList.RemoveAllChildren();
        if (_state == null)
            return;

        foreach (var o in _state.Outposts)
        {
            var btn = new Button
            {
                Text = $"{o.Name}  [{ControlLabel(o.Control)}]",
                ToggleMode = true,
                Pressed = _selected == o.Grid,
                HorizontalExpand = true,
                StyleClasses = { "ButtonSquare" },
            };

            var grid = o.Grid;
            btn.OnPressed += _ =>
            {
                _selected = grid;
                _map.SetState(_state, _selected);
                ShowDetail(grid);
                RebuildList();
            };

            OutpostList.AddChild(btn);
        }
    }

    private void OnOutpostClicked(NetEntity grid)
    {
        _selected = grid;
        if (_state != null)
            _map.SetState(_state, _selected);
        ShowDetail(grid);
        RebuildList();
    }

    private void ShowDetail(NetEntity grid)
    {
        if (_state == null)
        {
            DetailPanel.Visible = false;
            return;
        }

        SectorMapOutpostDto? found = null;
        foreach (var o in _state.Outposts)
        {
            if (o.Grid == grid)
            {
                found = o;
                break;
            }
        }

        if (found == null)
        {
            DetailPanel.Visible = false;
            return;
        }

        var usedOutpost = found.Value;
        DetailPanel.Visible = true;
        DetailName.Text = usedOutpost.Name;
        DetailOwner.Text = Loc.GetString("strategic-ui-owner",
            ("owner", usedOutpost.Owner?.Id ?? Loc.GetString("strategic-ui-owner-none")));
        DetailSector.Text = Loc.GetString("strategic-ui-sector",
            ("x", usedOutpost.SectorX), ("y", usedOutpost.SectorY));
        DetailCoords.Text = Loc.GetString("strategic-ui-coords",
            ("x", usedOutpost.WorldPos.X.ToString("F0")),
            ("y", usedOutpost.WorldPos.Y.ToString("F0")));

        usedOutpost.Pools.TryGetValue(StrategicResource.Fuel, out var fuel);
        usedOutpost.Pools.TryGetValue(StrategicResource.Munitions, out var munitions);
        usedOutpost.Pools.TryGetValue(StrategicResource.Parts, out var parts);

        DetailFuel.Text = Loc.GetString("strategic-ui-pool-fuel", ("amount", fuel));
        DetailMunitions.Text = Loc.GetString("strategic-ui-pool-munitions", ("amount", munitions));
        DetailParts.Text = Loc.GetString("strategic-ui-pool-parts", ("amount", parts));
    }

    private static string ControlLabel(SectorControl c) => c switch
    {
        SectorControl.Controlled => Loc.GetString("strategic-ui-control-controlled"),
        SectorControl.Contested => Loc.GetString("strategic-ui-control-contested"),
        _ => Loc.GetString("strategic-ui-control-unclaimed"),
    };
}
